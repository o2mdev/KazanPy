"""File writers of *File > Save Source*: ports of ``kv3_d01write`` (SpecMan ``.d01`` +
``.exp``), ``kv_brukerwrite`` (Bruker ``.DSC`` + ``.DTA``, ESP ``.par`` + ``.spc``) and
``kv_LMBwrite`` (WinSIM ``.LMB``). ASCII is :func:`kazan.io.ascii.ascii_write`.

Each file is written so that the matching KazanPy loader reads it back. Differences
from MATLAB are noted at each function.
"""
from __future__ import annotations

import struct
import time
from pathlib import Path

import numpy as np

from .ascii import ascii_write

#: Save Source formats: (dialog filter, writer key)
FORMATS = [('ASCII files (*.txt)', 'txt'), ('ASCII files (*.dat)', 'dat'),
           ('SpecMan files (*.d01)', 'd01'), ('Bruker files (new, *.dsc)', 'dsc'),
           ('Bruker files (old, *.par)', 'par'), ('WinSIM files (*.lmb)', 'lmb')]


def _y2d(d) -> np.ndarray:
    y = np.asarray(d.y)
    return y[:, None] if y.ndim == 1 else y


def _label(text: str) -> tuple[str, str]:
    """'Magnetic Field, G' -> ('Magnetic Field', 'G')."""
    name, _, unit = str(text or '').partition(',')
    return name.strip(), unit.strip()


def best_unit(val: float, unit: str) -> str:
    """``kv_bestunit``: the value with an SI prefix, e.g. 2e-7 's' -> '200 ns' (MATLAB
    dropped the sign)."""
    prefixes = [('p', 1e-12), ('n', 1e-9), ('u', 1e-6), ('m', 1e-3), ('', 1.0), ('k', 1e3),
                ('M', 1e6), ('G', 1e9), ('T', 1e12)]
    a = abs(val)
    pre, k = prefixes[-1]
    for (p0, k0), (_, k1) in zip(prefixes, prefixes[1:]):
        if a < k1:
            pre, k = p0, k0
            break
    return f'{val / k:g} {pre}{unit}'


# ---------------------------------------------------------------- SpecMan
def d01_write(filename: str, d, fmt: str = 'float'):
    """``kv3_d01write``: ``name.d01`` (little-endian header, float32 or double data,
    a second stream for the imaginary part) and ``name.exp``.

    Differences: an uneven axis lists its own values (MATLAB printed ``ax.y``); the
    origin is the source file name (MATLAB looked for a missing ``fname`` field)."""
    p = Path(filename)
    y = _y2d(d)
    dims = list(y.shape) + [1] * (4 - y.ndim)
    total = int(np.prod(dims))
    cplx = bool(np.any(np.imag(y)))
    nstreams = 2 if cplx else 1
    dt = '<f8' if fmt == 'double' else '<f4'
    with open(p.with_suffix('.d01'), 'wb') as f:
        f.write(struct.pack('<II', nstreams, 0 if fmt == 'double' else 1))
        for _ in range(nstreams):
            f.write(struct.pack('<i4ii', sum(n > 1 for n in dims), *dims, total))
        f.write(np.real(y).ravel(order='F').astype(dt).tobytes())
        if cplx:
            f.write(np.imag(y).ravel(order='F').astype(dt).tobytes())

    ax = d.ax
    lines = ['[general]', f"name = {ax.get('title') or ''}", '']
    try:
        if ax.get('freq1'):
            lines += [f'freq1 = {float(ax.freq1) * 1e-9:f} GHz', '']
    except (TypeError, ValueError):
        pass
    lines += ['[text]', 'Generated by Kazan Viewer', f"from '{d.filename or 'unknown'}'", '',
              '[sweep]', 'transient = I,1,1,a,b' if cplx else 'transient = I,1,1,a']
    axes = []
    for i, letter in enumerate('xyz'):
        if i < len(dims) and dims[i] != 1:
            name, unit = _label(ax.get(f'{letter}label') or ',')
            if not name or name == '?':
                name = 'no'
            if any(name == a[1] for a in axes):
                name = f'{name}{i + 1}'
            axes.append((letter, name, unit, dims[i]))
            lines.append(f'sweep{i} = {letter.upper()},{dims[i]},1,{name}')
    lines += ['', '[params]']
    for letter, name, unit, n in axes:
        v = ax.get(letter)
        v = np.ravel(v).astype(float) if v is not None and np.size(v) == n else np.arange(1.0, n + 1)
        dv = np.diff(v)
        if len(dv) == 0 or np.allclose(dv, dv[0], rtol=0.1, atol=0):
            lines.append(f'{name} = {v[0]:g} {unit} to {v[-1]:g} {unit}; {name}@none')
        else:
            lines.append(f"{name} = {', '.join(best_unit(a, unit) for a in v)}; {name}@none")
    lines += ['', '[aquisition]', 'a = '] + (['b = '] if cplx else [])
    if d.dsc:
        lines += ['', '[dsc]'] + _dsc_lines('', d.dsc)
    with open(p.with_suffix('.exp'), 'w', encoding='utf-8', newline='\r\n') as f:
        f.write('\n'.join(lines) + '\n')


def _dsc_lines(prefix: str, value) -> list[str]:
    """``print_fld``: nested description fields as ``a_b=value``."""
    if isinstance(value, dict):
        out = []
        for k, v in value.items():
            out += _dsc_lines(f'{prefix}_{k}' if prefix else str(k), v)
        return out
    if isinstance(value, str):
        return [f'{prefix}={value}']
    a = np.ravel(np.asarray(value)) if np.ndim(value) else np.asarray([value])
    if a.dtype.kind not in 'biuf':
        return []
    if a.size > 30:
        dd = np.diff(a)
        if np.allclose(dd, dd[0], rtol=0.02):
            return [f'{prefix}={a[0]:g} step {dd[0]:g}']
        return [f'{prefix}= ??']
    return [f"{prefix}={' '.join(f'{v:g}' for v in a)}"]


# ---------------------------------------------------------------- Bruker
def dsc_write(filename: str, d):
    """``kv_brukerwrite`` 'DSC': ``name.DTA`` (big-endian float64) and ``name.DSC``.
    A time axis in seconds is stored in ns, as in MATLAB.

    Differences: real data are written as REAL (MATLAB always wrote CPLX with a zero
    imaginary part); axis limits keep full precision (MATLAB ``%f``)."""
    p = Path(filename)
    y = _y2d(d)
    nx, ny = y.shape
    cplx = bool(np.any(np.imag(y)))
    flat = y.ravel(order='F')
    data = np.column_stack([flat.real, flat.imag]).ravel() if cplx else flat.real
    data.astype('>f8').tofile(p.with_suffix('.DTA'))

    ax = d.ax
    namex, unitx = _label(ax.get('xlabel') or '')
    x = np.ravel(ax.x).astype(float)
    if unitx == 's':
        namex, unitx, x = 'Time', 'ns', x * 1e9
    namey, unity = _label(ax.get('ylabel') or '')
    title = str(ax.get('title') or '').replace("'", '')
    lines = ['#DESC\t1.2 * DESCRIPTOR INFORMATION ***********************', '*',
             '*\tDataset Type and Format:', '*',
             f"DSRC\t{d.dsc.get('DSRC', 'EXP')}", 'BSEQ\tBIG', f"IKKF\t{'CPLX' if cplx else 'REAL'}",
             f"XTYP\t{'IDX' if nx > 1 else 'NODATA'}", f"YTYP\t{'IDX' if ny > 1 else 'NODATA'}",
             'ZTYP\tNODATA', '*', '*\tItem Formats:', '*', 'IRFMT\tD', 'IIFMT\tD', '*',
             '*\tData Ranges and Resolutions:', '*',
             f'XPTS\t{nx}', f'XMIN\t{x.min():.12g}', f'XWID\t{x.max() - x.min():.12g}']
    if ny > 1:
        yv = np.ravel(ax.y).astype(float) if ax.get('y') is not None and np.size(ax.y) == ny else np.arange(1.0, ny + 1)
        lines += [f'YPTS\t{ny}', f'YMIN\t{yv.min():.12g}', f'YWID\t{yv.max() - yv.min():.12g}']
    lines += ['*', '*\tDocumentational Text:', '*', f"TITL\t'{title}'", "IRNAM\t'Intensity'",
              "IINAM\t'Intensity'", f"XNAM\t'{namex}'", "IRUNI\t''", "IIUNI\t''", f"XUNI\t'{unitx}'"]
    if ny > 1:
        lines += [f"YNAM\t'{namey}'", f"YUNI\t'{unity}'"]
    lines += ['*', '************************************************************', '*',
              '#SPL\t1.2 * STANDARD PARAMETER LAYER', '*', 'OPER    KazanViewer',
              f"DATE    {time.strftime('%d/%m/%y')}", f"TIME    {time.strftime('%H:%M:%S')}",
              f"CMNT    {ax.get('comment') or ''}", f"SAMP    {ax.get('sample') or ''}",
              f"SFOR    {ax.get('formula') or ''}", f'MWFQ    {_float(ax.get("freq1")):.1f}',
              '*  Generated by KazanPy (Kazan Viewer 3.0 port)']
    with open(p.with_suffix('.DSC'), 'w', encoding='latin-1', errors='replace', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


def par_write(filename: str, d):
    """``kv_brukerwrite`` 'PAR': ESP/WinEPR ``name.par`` (parameters) + ``name.spc``
    (data), 1D only.

    Differences: MATLAB wrote the data into ``.par`` and the parameters into ``.spc``
    (swapped), as big-endian int32 (rounded to integers), with a fixed field axis
    (GST 462.1, GSI 99.8). Here the data are WinEPR float32 (``DOS Format``) and the
    field axis is taken from the data (``JSS 2``: GST / GSI / HCF / HSW / RES)."""
    p = Path(filename)
    y = _y2d(d)
    if y.shape[1] != 1:
        raise ValueError('The ESP .par format holds 1D data only (use Cut Slice first)')
    np.real(y[:, 0]).astype('<f4').tofile(p.with_suffix('.spc'))
    x = np.ravel(d.ax.x).astype(float)
    x0, x1 = float(x.min()), float(x.max())
    n = len(x)
    pars = [('DOS', 'Format'), ('JSS', '2'), ('JON', ''), ('JRE', 'SHQ'),
            ('JDA', time.strftime('%m/%d/%Y')), ('JTM', time.strftime('%H:%M')),
            ('JCO', str(d.ax.get('comment') or '')), ('JUN', 'Gauss'), ('JNS', '1'),
            ('JSD', '0'), ('JEX', 'EPR'), ('JAR', 'Add'),
            ('GST', f'{x0:.10g}'), ('GSI', f'{x1 - x0:.10g}'), ('TE', '0'),
            ('HCF', f'{(x0 + x1) / 2:.10g}'), ('HSW', f'{x1 - x0:.10g}'),
            ('MF', f'{_float(d.ax.get("freq1")) * 1e-9:.6g}'), ('RES', str(n)), ('ANZ', str(n))]
    with open(p.with_suffix('.par'), 'w', encoding='latin-1', errors='replace', newline='\r\n') as f:
        f.write('\n'.join(f'{k:<6} {v}'.rstrip() for k, v in pars) + '\n')


# ---------------------------------------------------------------- WinSIM
def lmb_write(filename: str, d):
    """``kv_LMBwrite``: WinSIM ``name.LMB``: 'ESR2', 20 float32 parameters (sweep width,
    centre field, points, ...), float32 data, a 60-character comment, 20 12-character
    parameter strings and two 60-character comments; 1D only.

    Differences: the comment is the title and the strings hold the centre field, sweep,
    frequency, date and time of the data (MATLAB wrote fixed example values such as
    '9.33GHz' and '3-12-94'); the two extra comments are 60 characters each (MATLAB
    wrote one character)."""
    p = Path(filename)
    y = _y2d(d)
    if y.shape[1] != 1:
        raise ValueError('The LMB format holds 1D data only (use Cut Slice first)')
    x = np.ravel(d.ax.x).astype(float)
    sw, cf, n = x.max() - x.min(), (x.max() + x.min()) / 2, len(x)
    head = [sw, cf, n, 1, 1, 0, 0, 1, n, 20] + [0] * 10
    freq = _float(d.ax.get('freq1'))
    strings = [''] * 20
    strings[6], strings[7] = f'{cf:.3f}', f'{sw:.1f}'
    strings[8] = f'{freq * 1e-9:.2f}GHz' if freq else ''
    strings[9], strings[10] = time.strftime('%m-%d-%y'), time.strftime('%H:%M')
    title = str(d.ax.get('title') or '')[:60]
    with open(p.with_suffix('.LMB'), 'wb') as f:
        f.write(b'ESR2')
        f.write(np.asarray(head, '<f4').tobytes())
        f.write(np.real(y[:, 0]).astype('<f4').tobytes())
        f.write(f'{title:<60}'.encode('latin-1', 'replace'))
        for s in strings:
            f.write(f'{s[:12]:<12}'.encode('latin-1', 'replace'))
        f.write(b' ' * 120)


def lmb_read(filename: str):
    """Reader from the comment in ``kv_LMBwrite`` (used to check the writer)."""
    b = Path(filename).read_bytes()
    pars = np.frombuffer(b, '<f4', count=20, offset=4)
    n = int(pars[2])
    y = np.frombuffer(b, '<f4', count=n, offset=84).astype(float)
    pos = 84 + 4 * n
    comment = b[pos:pos + 60].decode('latin-1').strip()
    strings = [b[pos + 60 + 12 * i:pos + 72 + 12 * i].decode('latin-1').strip() for i in range(20)]
    x = pars[1] - pars[0] / 2 + pars[0] * np.arange(n) / max(n - 1, 1)
    return x, y, comment, strings


def _float(v) -> float:
    try:
        return float(v or 0)
    except (TypeError, ValueError):
        return 0.0


def save(filename: str, d, kind: str, parameters=None):
    """Write ``d`` in format ``kind`` (``FORMATS`` keys)."""
    if kind in ('txt', 'dat'):
        ascii_write(filename, d, origin=d.filename or '', parameters=parameters)
    elif kind == 'd01':
        d01_write(filename, d)
    elif kind == 'dsc':
        dsc_write(filename, d)
    elif kind == 'par':
        par_write(filename, d)
    elif kind == 'lmb':
        lmb_write(filename, d)
    else:
        raise ValueError(f'Unknown format {kind!r}')
